// Qwen3-8B inference engine for one logical NeuronCore of a Trainium2 (engine protocol 1, JSON lines on stdin/stdout).
//
// The host loads the checkpoint, lays the weights out for the kernels (transposes, LM head swizzle) and uploads
// them once, then schedules NEFFs (compiled NKI kernels embedded in this executable) through libnrt. Every layer of
// the forward pass, the LM head and the argmax run on the NeuronCore; the host only moves token ids and positions.
