// ------------------------------------------------------------------------------------------------ model constants
static const int H = 4096, NQ = 32, NKV = 8, D = 128, I = 12288, L = 36, V = 151936;
static const int QKV = (NQ + 2 * NKV) * D;  // 6144
static const int SMAX = 4608;               // KV cache positions
static const int VC = 149, VP = 2 * VC * 512;  // LM head chunks per core, padded vocabulary
static const int PRE_T[] = {128, 256, 512, 1024, 2048, 4096, 4608};
static const int DEC_S[] = {384, 512, 1024, 1152, 1536, 2048, 3072, 4224, 4608};  // kernels/build_neffs.py DEC_S
static const double ROPE_THETA = 1e6;
static const int NLD = 12;                                 // decode layers per NEFF (kernels/build_neffs.py)
static const int NLP = 5;                                   // prefill layers per NEFF, T <= 512 (kernels/build_neffs.py)
static const int NCH = 6;                                  // most prefill MLP chunks of any bucket
static int nch(int T) { return T <= 512 ? 3 : 6; }         // kernels/build_neffs.py nch()
static bool qkva_T(int T) { return T <= 1024; }              // kernels/build_neffs.py: pre_layers for T <= 1024
static bool small_T(int) { return true; }                    // kernels/build_neffs.py PRE_SMALL (all buckets)

// ------------------------------------------------------------------------------------------------ embedded NEFFs
struct NeffBlob { const char* name; const char* start; const char* end; };
#include "neffs.inc"  // generated by build.sh: extern symbols and `static const NeffBlob NEFFS[]`

using clk = std::chrono::steady_clock;
static double ms_since(clk::time_point t) { return std::chrono::duration<double, std::milli>(clk::now() - t).count(); }

static void die(const std::string& m) { fprintf(stderr, "fatal: %s\n", m.c_str()); exit(1); }
#define CK(x) do { NRT_STATUS s_ = (x); if (s_ != NRT_SUCCESS) { \
  throw std::runtime_error(std::string(#x) + " -> " + std::to_string((int)s_) + " " + nrt_get_status_as_str(s_)); } } while (0)

static uint16_t f2bf(float f) { uint32_t u; memcpy(&u, &f, 4); u += 0x7fff + ((u >> 16) & 1); return (uint16_t)(u >> 16); }

// ------------------------------------------------------------------------------------------------ thread pool helper
static void parallel_for(size_t n, const std::function<void(size_t)>& fn, int threads = 0) {
  if (threads <= 0) threads = std::max(1u, std::min(64u, std::thread::hardware_concurrency()));
  std::atomic<size_t> next{0};
  std::vector<std::thread> ts;
  for (int t = 0; t < threads; t++)
    ts.emplace_back([&] { for (size_t i; (i = next.fetch_add(1)) < n;) fn(i); });
  for (auto& t : ts) t.join();
}

// ------------------------------------------------------------------------------------------------ safetensors
struct TensorRef { const uint16_t* data; std::vector<int64_t> shape; };

class Checkpoint {
 public:
  explicit Checkpoint(const std::string& dir) : dir_(dir) {
    std::string idx = slurp(dir + "/model.safetensors.index.json");
    json::Value v = json::parse(idx);
    for (auto& kv : v.at("weight_map").obj) {
      const std::string& file = kv.second.s;
      if (!files_.count(file)) open_shard(file);
      names_[kv.first] = file;
    }
  }
  TensorRef get(const std::string& name, std::vector<int64_t> expect) const {
    auto it = tensors_.find(name);
    if (it == tensors_.end()) die("tensor not found: " + name);
    if (it->second.shape != expect) die("unexpected shape for " + name);
    return it->second;
  }

 private:
  static std::string slurp(const std::string& p) {
    FILE* f = fopen(p.c_str(), "rb");
    if (!f) die("cannot open " + p);
    std::string s;
    char buf[1 << 16];
    size_t n;
    while ((n = fread(buf, 1, sizeof buf, f)) > 0) s.append(buf, n);
    fclose(f);
    return s;
  }
  void open_shard(const std::string& file) {
    std::string p = dir_ + "/" + file;
    int fd = open(p.c_str(), O_RDONLY);
    if (fd < 0) die("cannot open " + p);
    struct stat st;
    fstat(fd, &st);
    void* base = mmap(nullptr, st.st_size, PROT_READ, MAP_PRIVATE, fd, 0);
    if (base == MAP_FAILED) die("mmap failed: " + p);
    close(fd);
    madvise(base, st.st_size, MADV_WILLNEED);
    files_[file] = base;
    uint64_t hl;
    memcpy(&hl, base, 8);
    const char* hdr = (const char*)base + 8;
    json::Value h = json::parse(hdr, hl);
    const char* data = hdr + hl;
    for (auto& kv : h.obj) {
      if (kv.first == "__metadata__") continue;
      if (kv.second.at("dtype").s != "BF16") die("expected BF16 for " + kv.first);
      TensorRef r;
      for (auto& d : kv.second.at("shape").arr) r.shape.push_back(d.as_int());
      r.data = (const uint16_t*)(data + kv.second.at("data_offsets").arr[0].as_int());
      tensors_[kv.first] = r;
    }
  }
  std::string dir_;
  std::map<std::string, void*> files_;
  std::map<std::string, std::string> names_;
  std::map<std::string, TensorRef> tensors_;
};

// dst[c][r] (row stride ld, starting at column col0) = src[r][c], src [R][C]
static void transpose_into(const uint16_t* src, int64_t R, int64_t C, uint16_t* dst, int64_t ld, int64_t col0) {
  const int64_t B = 64;
  int64_t nb = (C + B - 1) / B;
  parallel_for(nb, [&](size_t cb) {
    int64_t c0 = cb * B, c1 = std::min(C, c0 + B);
    for (int64_t r0 = 0; r0 < R; r0 += B) {
      int64_t r1 = std::min(R, r0 + B);
      for (int64_t c = c0; c < c1; c++) {
        uint16_t* d = dst + c * ld + col0;
        for (int64_t r = r0; r < r1; r++) d[r] = src[r * C + c];
      }
    }
  });
}

// ------------------------------------------------------------------------------------------------ libnrt wrappers
struct Model {
  std::string name;
  nrt_model_t* m = nullptr;
  std::map<std::string, size_t> in_size, out_size;
};

struct Call {
  Model* model = nullptr;
  nrt_tensor_set_t* ins = nullptr;
  nrt_tensor_set_t* outs = nullptr;
};

static nrt_tensor_t* dev_alloc(size_t bytes, const std::string& name) {
  nrt_tensor_t* t;
  CK(nrt_tensor_allocate(NRT_TENSOR_PLACEMENT_DEVICE, 0, bytes, name.c_str(), &t));
  return t;
}
static nrt_tensor_t* dev_slice(nrt_tensor_t* src, size_t bytes, const std::string& name, size_t offset = 0) {
  nrt_tensor_t* t;
  CK(nrt_tensor_allocate_slice(src, offset, bytes, name.c_str(), &t));
  return t;
}
static size_t tsize(nrt_tensor_t* t) { return nrt_tensor_get_size(t); }

class Engine {
 public:
  explicit Engine(const std::string& model_dir) : dir_(model_dir) {}

  void load() {
    auto t0 = clk::now();
    CK(nrt_init(NRT_FRAMEWORK_TYPE_NO_FW, "", ""));
    for (const NeffBlob& b : NEFFS) {
      Model& m = models_[b.name];
      m.name = b.name;
      CK(nrt_load(b.start, b.end - b.start, 0, 1, &m.m));
      nrt_tensor_info_array_t* info;
      CK(nrt_get_model_tensor_info(m.m, &info));
      for (uint64_t i = 0; i < info->tensor_count; i++) {
        auto& t = info->tensor_array[i];
        (t.usage == NRT_TENSOR_USAGE_INPUT ? m.in_size : m.out_size)[t.name] = t.size;
        if (getenv("ENGINE_INFO")) fprintf(stderr, "  %s %s %s %zu\n", b.name, t.usage == NRT_TENSOR_USAGE_INPUT ? "in " : "out", t.name, t.size);
      }
      nrt_free_model_tensor_info(info);
    }
    fprintf(stderr, "loaded %zu NEFFs in %.0f ms\n", models_.size(), ms_since(t0));
    alloc_buffers();
    load_weights();
    build_calls();
    // First executions of a model with its tensor set are slow (1 to 3 ms per call measured): run every call once.
    auto tw = clk::now();
    for (int T : PRE_T) prefill(std::vector<int>(T, 0));
    for (int S : DEC_S) decode_step(0, S - 1);
    have_state_ = false;
    fprintf(stderr, "warm-up %.1f s; engine ready in %.1f s\n", ms_since(tw) / 1e3, ms_since(t0) / 1e3);
  }

  // generate per the protocol; returns the emitted tokens
  std::vector<int> generate(const std::vector<int>& prompt, int max_tokens, bool reset) {
    std::vector<int> out;
    if (max_tokens < 1) throw std::runtime_error("max_tokens must be at least 1");
    if (reset) {
      if (prompt.empty()) throw std::runtime_error("a reset request needs a prompt");
      int P = (int)prompt.size();
      if (P > PRE_T[std::size(PRE_T) - 1]) throw std::runtime_error("prompt longer than the compiled maximum");
      if (P + max_tokens - 1 > SMAX) throw std::runtime_error("request exceeds the KV cache length");
      for (int t : prompt) if (t < 0 || t >= V) throw std::runtime_error("token id out of range");
      have_state_ = false;
      int tok = prefill(prompt);
      consumed_ = P;
      pending_ = tok;
      have_state_ = true;
      out.push_back(tok);
    } else {
      if (!prompt.empty()) throw std::runtime_error("a continuation has an empty prompt");
      if (!have_state_) throw std::runtime_error("a continuation needs an earlier generate");
      if (consumed_ + max_tokens > SMAX) throw std::runtime_error("request exceeds the KV cache length");
    }
    while ((int)out.size() < max_tokens) {
      int tok = decode_step(pending_, consumed_);
      consumed_++;
      pending_ = tok;
      out.push_back(tok);
    }
    return out;
  }

 private:
  // ---------------------------------------------------------------------------------------------- buffers
  struct LayerW {
    nrt_tensor_t *g1, *g1c, *wqkv, *qn, *kn, *wo, *g2, *g2c, *wg, *wu, *wd, *kc, *vc;
  };
  std::string dir_;
  std::map<std::string, Model> models_;
  std::vector<LayerW> lw_;
  struct Stacked { nrt_tensor_t* all; size_t per; };
  std::map<std::string, Stacked> stacked_;
  // the slice of layers [l0, l0 + n) of a stacked kind
  nrt_tensor_t* group(const std::string& kind, int l0, int n) {
    Stacked& st = stacked_.at(kind);
    return dev_slice(st.all, st.per * n, kind + "_grp", st.per * l0);
  }
  nrt_tensor_t *rot_, *rcT_, *rsT_, *emb_, *gf_, *wlm_, *cos_dec_, *sin_dec_, *rope_cos_, *rope_sin_, *mask_;
  std::map<int, nrt_tensor_t*> sctx_;          // decode bucket marker tensors
  std::map<int, std::vector<nrt_tensor_t*>> chunk_;  // per chunk count: marker tensors [n, c+1]
  // decode state buffers
  nrt_tensor_t *off_, *tok_, *pos_, *xd_[2], *cosd_, *sind_, *posf_, *posu_, *logits_, *logits_v_, *amax_v_, *amax_i_;
  // prefill buffers (allocated for the largest bucket; sliced per bucket)
  nrt_tensor_t *toks_, *xp_[2], *q_[2], *k_[2], *v_[2], *a_[2], *hp_, *m_[2], *dummy_;

  struct DecCalls { Call embed; std::vector<std::vector<Call>> layer; std::vector<Call> last; Call head, amax; } dec_;
  struct PreCalls { bool small = true; int tb = 0; Call embed, xrow; std::vector<Call> layers, qkva, qkv, cache, attn, oproj, mlp[NCH], post; nrt_tensor_t* toks; nrt_tensor_t* xout; };
  std::map<int, PreCalls> pre_;

  bool have_state_ = false;
  bool prof_ = getenv("ENGINE_PROF") != nullptr;
  bool step_t_ = getenv("ENGINE_STEPT") != nullptr;
  double step_gap_ms_ = 0, step_w_ms_ = 0, step_pre_ms_ = 0; int step_n_ = 0; clk::time_point last_wait_end_ = clk::now();
 public:
  void step_report() { if (step_t_ && step_n_) fprintf(stderr, "  host gap per token %.3f ms (before writes %.3f, writes %.3f) over %d steps\n", step_gap_ms_ / step_n_, step_pre_ms_ / step_n_, step_w_ms_ / step_n_, step_n_); step_gap_ms_ = step_w_ms_ = step_pre_ms_ = 0; step_n_ = 0; }
 private:
  std::map<std::string, double> prof_ms_;
  std::map<std::string, int> prof_n_;
 public:
  void report() { prof_report(); }
 private:
  int consumed_ = 0, pending_ = 0;

  void alloc_buffers() {
    const size_t bf = 2;
    emb_ = dev_alloc((size_t)V * H * bf, "emb");
    gf_ = dev_alloc(H * bf, "gf");
    wlm_ = dev_alloc((size_t)VP * H * bf, "wlm");
    lw_.resize(L);
    // Every per-layer tensor kind is one allocation for all L layers: prefill uses one layer's slice, a decode NEFF
    // the slice of its NLD consecutive layers (stacked inputs).
    auto stack = [&](const char* name, size_t per, nrt_tensor_t* LayerW::*field) {
      nrt_tensor_t* all = dev_alloc(per * L, std::string(name) + "_all");
      stacked_[name] = {all, per};
      for (int l = 0; l < L; l++) lw_[l].*field = dev_slice(all, per, std::string(name) + std::to_string(l), per * l);
    };
    stack("g1", H * bf, &LayerW::g1);
    stack("g1c", H * bf, &LayerW::g1c);
    stack("g2", H * bf, &LayerW::g2);
    stack("g2c", H * bf, &LayerW::g2c);
    stack("qn", D * bf, &LayerW::qn);
    stack("kn", D * bf, &LayerW::kn);
    stack("wqkv", (size_t)H * QKV * bf, &LayerW::wqkv);
    stack("wo", (size_t)NQ * D * H * bf, &LayerW::wo);
    stack("wg", (size_t)H * I * bf, &LayerW::wg);
    stack("wu", (size_t)H * I * bf, &LayerW::wu);
    stack("wd", (size_t)I * H * bf, &LayerW::wd);
    stack("kc", (size_t)NKV * SMAX * D * bf, &LayerW::kc);
    stack("vc", (size_t)NKV * SMAX * D * bf, &LayerW::vc);
    for (const char* c : {"kc", "vc"}) CK(nrt_tensor_memset(stacked_[c].all, 0, 0, tsize(stacked_[c].all)));
    // RoPE tables (constants of the model, like inv_freq): decode [SMAX, D/2], prefill [SMAX, D] (halves repeated)
    std::vector<uint16_t> cd((size_t)SMAX * D / 2), sd((size_t)SMAX * D / 2), cp((size_t)SMAX * D), sp((size_t)SMAX * D);
    for (int p = 0; p < SMAX; p++)
      for (int j = 0; j < D / 2; j++) {
        // as HF: inv_freq = 1 / theta^(2j/D) in float32, freqs = pos * inv_freq in float32, cos/sin in float32
        float inv = (float)(1.0 / pow(ROPE_THETA, (double)(2 * j) / D));
        float ang = (float)p * inv;
        uint16_t c = f2bf(cosf(ang)), s = f2bf(sinf(ang));
        cd[(size_t)p * D / 2 + j] = c; sd[(size_t)p * D / 2 + j] = s;
        cp[(size_t)p * D + j] = c; cp[(size_t)p * D + j + D / 2] = c;
        sp[(size_t)p * D + j] = s; sp[(size_t)p * D + j + D / 2] = s;
      }
    cos_dec_ = dev_alloc(cd.size() * bf, "cos_dec"); CK(nrt_tensor_write(cos_dec_, cd.data(), 0, cd.size() * bf));
    sin_dec_ = dev_alloc(sd.size() * bf, "sin_dec"); CK(nrt_tensor_write(sin_dec_, sd.data(), 0, sd.size() * bf));
    {  // transposed prefill tables [D, SMAX] for the small-T kernels
      std::vector<uint16_t> ct((size_t)D * SMAX), st((size_t)D * SMAX);
      for (int p = 0; p < SMAX; p++)
        for (int d = 0; d < D; d++) { ct[(size_t)d * SMAX + p] = cp[(size_t)p * D + d]; st[(size_t)d * SMAX + p] = sp[(size_t)p * D + d]; }
      rcT_ = dev_alloc(ct.size() * bf, "rcT"); CK(nrt_tensor_write(rcT_, ct.data(), 0, ct.size() * bf));
      rsT_ = dev_alloc(st.size() * bf, "rsT"); CK(nrt_tensor_write(rsT_, st.data(), 0, st.size() * bf));
    }
    rope_cos_ = dev_alloc(cp.size() * bf, "rope_cos"); CK(nrt_tensor_write(rope_cos_, cp.data(), 0, cp.size() * bf));
    rope_sin_ = dev_alloc(sp.size() * bf, "rope_sin"); CK(nrt_tensor_write(rope_sin_, sp.data(), 0, sp.size() * bf));
    {  // rotate_half as a matrix for the decode layer: rot[k][m] = -1 if k = m + 64, +1 if k = m - 64
      std::vector<uint16_t> r((size_t)D * D, 0);
      for (int m = 0; m < D; m++) r[(size_t)(m < D / 2 ? m + D / 2 : m - D / 2) * D + m] = m < D / 2 ? 0xbf80 : 0x3f80;
      rot_ = dev_alloc(r.size() * bf, "rot"); CK(nrt_tensor_write(rot_, r.data(), 0, r.size() * bf));
    }
    std::vector<uint8_t> ones(NQ, 1);
    mask_ = dev_alloc(NQ, "mask"); CK(nrt_tensor_write(mask_, ones.data(), 0, NQ));
    for (int S : DEC_S) { sctx_[S] = dev_alloc(S, "sctx" + std::to_string(S)); CK(nrt_tensor_memset(sctx_[S], 0, 0, S)); }
    for (int n : {3, 6})
      for (int c = 0; c < n; c++) {
        nrt_tensor_t* t = dev_alloc(n * (c + 1), "chunk");
        CK(nrt_tensor_memset(t, 0, 0, n * (c + 1)));
        chunk_[n].push_back(t);
      }
    // decode
    off_ = dev_alloc(4, "off");
    tok_ = dev_alloc(4, "tok"); pos_ = dev_alloc(4, "pos");
    xd_[0] = dev_alloc(H * bf, "xd0"); xd_[1] = dev_alloc(H * bf, "xd1");
    cosd_ = dev_alloc(D / 2 * bf, "cosd"); sind_ = dev_alloc(D / 2 * bf, "sind");
    posf_ = dev_alloc(4, "posf"); posu_ = dev_alloc(4, "posu");
    logits_ = dev_alloc((size_t)VP * 4, "logits"); logits_v_ = dev_slice(logits_, (size_t)V * 4, "logits_v");
    amax_v_ = dev_alloc(4, "amax_v"); amax_i_ = dev_alloc(4, "amax_i");
    // prefill
    const int TM = PRE_T[std::size(PRE_T) - 1];
    toks_ = dev_alloc((size_t)TM * 4, "toks");
    for (int i = 0; i < 2; i++) {
      xp_[i] = dev_alloc((size_t)TM * H * bf, "xp" + std::to_string(i));
      q_[i] = dev_alloc((size_t)NQ * TM * D * bf, "q" + std::to_string(i));    // all heads (own prefill kernels)
      k_[i] = dev_alloc((size_t)NKV * TM * D * bf, "k" + std::to_string(i));
      v_[i] = dev_alloc((size_t)NKV * TM * D * bf, "v" + std::to_string(i));
      a_[i] = dev_alloc((size_t)NQ * TM * D * bf, "a" + std::to_string(i));
    }
    hp_ = dev_alloc((size_t)TM * H * bf, "hp");
    for (int c = 0; c < 2; c++) m_[c] = dev_alloc((size_t)TM * H * bf, "m" + std::to_string(c));
    dummy_ = dev_alloc(4, "dummy");
  }

  void load_weights() {
    auto t0 = clk::now();
    Checkpoint ck(dir_);
    auto upload = [&](nrt_tensor_t* t, const void* p, size_t n) { CK(nrt_tensor_write(t, p, 0, n)); };
    {
      TensorRef e = ck.get("model.embed_tokens.weight", {V, H});
      upload(emb_, e.data, (size_t)V * H * 2);
      TensorRef g = ck.get("model.norm.weight", {H});
      upload(gf_, g.data, H * 2);
      // LM head: wlm[c][j][p][kt][n] = W[(c*VC + j)*512 + n][kt*128 + p], zero beyond V
      TensorRef w = ck.get("lm_head.weight", {V, H});
      std::vector<uint16_t> s((size_t)VP * H);
      const int KT = H / 128;
      parallel_for(2 * VC, [&](size_t cj) {
        uint16_t* dst = s.data() + cj * (size_t)128 * KT * 512;
        for (int p = 0; p < 128; p++)
          for (int kt = 0; kt < KT; kt++)
            for (int n = 0; n < 512; n++) {
              int64_t col = (int64_t)cj * 512 + n;
              dst[((size_t)p * KT + kt) * 512 + n] = col < V ? w.data[col * H + kt * 128 + p] : 0;
            }
      });
      upload(wlm_, s.data(), s.size() * 2);
    }
    std::vector<uint16_t> buf((size_t)H * I);
    for (int l = 0; l < L; l++) {
      std::string p = "model.layers." + std::to_string(l) + ".";
      LayerW& w = lw_[l];
      {
        const uint16_t* g1 = ck.get(p + "input_layernorm.weight", {H}).data;
        upload(w.g1, g1, H * 2);
        std::vector<uint16_t> gc(H);  // column layout [128, H/128]: gc[p][t] = g1[t*128 + p]
        for (int t = 0; t < H / 128; t++) for (int q = 0; q < 128; q++) gc[(size_t)q * (H / 128) + t] = g1[t * 128 + q];
        upload(w.g1c, gc.data(), H * 2);
      }
      {
        const uint16_t* g2 = ck.get(p + "post_attention_layernorm.weight", {H}).data;
        upload(w.g2, g2, H * 2);
        std::vector<uint16_t> gc(H);  // column layout [128, H/128]: gc[p][t] = g2[t*128 + p]
        for (int t = 0; t < H / 128; t++) for (int q = 0; q < 128; q++) gc[(size_t)q * (H / 128) + t] = g2[t * 128 + q];
        upload(w.g2c, gc.data(), H * 2);
      }
      upload(w.qn, ck.get(p + "self_attn.q_norm.weight", {D}).data, D * 2);
      upload(w.kn, ck.get(p + "self_attn.k_norm.weight", {D}).data, D * 2);
      {  // [in, out] with the output columns grouped per core: [core c: q heads 16c.. | k heads 4c.. | v heads 4c..]
        const uint16_t* wq = ck.get(p + "self_attn.q_proj.weight", {NQ * D, H}).data;
        const uint16_t* wk = ck.get(p + "self_attn.k_proj.weight", {NKV * D, H}).data;
        const uint16_t* wv = ck.get(p + "self_attn.v_proj.weight", {NKV * D, H}).data;
        const int CQ = NQ / 2 * D, CK = NKV / 2 * D, CW = CQ + 2 * CK;
        for (int c = 0; c < 2; c++) {
          transpose_into(wq + (size_t)c * CQ * H, CQ, H, buf.data(), QKV, c * CW);
          transpose_into(wk + (size_t)c * CK * H, CK, H, buf.data(), QKV, c * CW + CQ);
          transpose_into(wv + (size_t)c * CK * H, CK, H, buf.data(), QKV, c * CW + CQ + CK);
        }
      }
      upload(w.wqkv, buf.data(), (size_t)H * QKV * 2);
      transpose_into(ck.get(p + "self_attn.o_proj.weight", {H, NQ * D}).data, H, NQ * D, buf.data(), H, 0);
      upload(w.wo, buf.data(), (size_t)NQ * D * H * 2);
      transpose_into(ck.get(p + "mlp.gate_proj.weight", {I, H}).data, I, H, buf.data(), I, 0);
      upload(w.wg, buf.data(), (size_t)H * I * 2);
      transpose_into(ck.get(p + "mlp.up_proj.weight", {I, H}).data, I, H, buf.data(), I, 0);
      upload(w.wu, buf.data(), (size_t)H * I * 2);
      transpose_into(ck.get(p + "mlp.down_proj.weight", {H, I}).data, H, I, buf.data(), H, 0);
      upload(w.wd, buf.data(), (size_t)I * H * 2);
    }
    fprintf(stderr, "weights uploaded in %.1f s\n", ms_since(t0) / 1e3);
  }

  // A model executed with several tensor sets pays for re-binding on every switch (measured: 2.7 ms per
  // nrta_execute_schedule of a decode layer), so each (NEFF, instance) pair gets its own loaded copy.
  Model* instance(const std::string& neff, int inst) {
    if (inst < 0) {
      auto it = models_.find(neff);
      if (it == models_.end()) die("NEFF not embedded: " + neff);
      return &it->second;
    }
    std::string key = neff + "#" + std::to_string(inst);
    auto it = models_.find(key);
    if (it != models_.end()) return &it->second;
    const NeffBlob* blob = nullptr;
    for (const NeffBlob& b : NEFFS) if (neff == b.name) blob = &b;
    if (!blob) die("NEFF not embedded: " + neff);
    Model& base = models_.at(neff);
    Model& m = models_[key];
    m.name = neff;
    m.in_size = base.in_size;
    m.out_size = base.out_size;
    CK(nrt_load(blob->start, blob->end - blob->start, 0, 1, &m.m));
    return &m;
  }

  Call make_call(const std::string& neff, const std::vector<std::pair<std::string, nrt_tensor_t*>>& ins,
                 const std::vector<nrt_tensor_t*>& outs, int inst = -1) {
    Model* model = instance(neff, inst);
    Call c;
    c.model = model;
    CK(nrt_allocate_tensor_set(&c.ins));
    CK(nrt_allocate_tensor_set(&c.outs));
    if (ins.size() != c.model->in_size.size()) die(neff + ": input count mismatch");
    for (auto& [name, t] : ins) {
      auto s = c.model->in_size.find(name);
      if (s == c.model->in_size.end()) die(neff + ": no input " + name);
      if (s->second != tsize(t)) die(neff + ": size mismatch for " + name + " (" + std::to_string(s->second) + " vs " + std::to_string(tsize(t)) + ")");
      CK(nrt_add_tensor_to_tensor_set(c.ins, name.c_str(), t));
    }
    if (outs.size() != c.model->out_size.size()) die(neff + ": output count mismatch");
    for (size_t i = 0; i < outs.size(); i++) {
      std::string name = "output_" + std::to_string(i);
      auto s = c.model->out_size.find(name);
      if (s == c.model->out_size.end()) die(neff + ": no output " + name);
      if (s->second != tsize(outs[i])) die(neff + ": size mismatch for " + name + " (" + std::to_string(s->second) + " vs " + std::to_string(tsize(outs[i])) + ")");
      CK(nrt_add_tensor_to_tensor_set(c.outs, name.c_str(), outs[i]));
    }
    return c;
  }

  void build_calls() {
    const size_t bf = 2;
    dec_.embed = make_call("embed_dec", {{"tok", tok_}, {"pos", pos_}, {"emb", emb_}, {"cos_tab", cos_dec_}, {"sin_tab", sin_dec_}},
                           {xd_[0], cosd_, sind_, posf_, posu_});
    for (int S : DEC_S) {
      std::vector<Call> v;
      for (int g = 0; g < L / NLD; g++) {
        int l0 = g * NLD;
        auto G = [&](const char* k) { return group(k, l0, NLD); };
        v.push_back(make_call("layer_dec_" + std::to_string(S),
                              {{"x", xd_[g % 2]}, {"g1c", G("g1c")}, {"wqkv", G("wqkv")}, {"qn", G("qn")}, {"kn", G("kn")},
                               {"rcos", rope_cos_}, {"rsin", rope_sin_}, {"rot", rot_}, {"kc", G("kc")}, {"vc", G("vc")},
                               {"pos", pos_}, {"posf", posf_}, {"wo", G("wo")}, {"g2c", G("g2c")}, {"wg", G("wg")},
                               {"wu", G("wu")}, {"wd", G("wd")}, {"sctx", sctx_[S]}},
                              {xd_[(g + 1) % 2]}, g));
      }
      dec_.layer.push_back(std::move(v));
      {  // the last layer alone (prefill: only the last prompt token needs its attention output and MLP)
        auto G = [&](const char* k) { return group(k, L - 1, 1); };
        dec_.last.push_back(make_call("layer_dec1_" + std::to_string(S),
                                      {{"x", xd_[0]}, {"g1c", G("g1c")}, {"wqkv", G("wqkv")}, {"qn", G("qn")}, {"kn", G("kn")},
                                       {"rcos", rope_cos_}, {"rsin", rope_sin_}, {"rot", rot_}, {"kc", G("kc")}, {"vc", G("vc")},
                                       {"pos", pos_}, {"posf", posf_}, {"wo", G("wo")}, {"g2c", G("g2c")}, {"wg", G("wg")},
                                       {"wu", G("wu")}, {"wd", G("wd")}, {"sctx", sctx_[S]}},
                                      {xd_[1]}, 100 + (int)dec_.layer.size()));
      }
    }
    dec_.head = make_call("lm_head", {{"x", xd_[(L / NLD) % 2]}, {"gf", gf_}, {"wlm", wlm_}}, {logits_});
    dec_.amax = make_call("argmax", {{"input_tensor", logits_v_}}, {amax_v_, amax_i_});
    for (int T : PRE_T) {
      std::string s = "_" + std::to_string(T);
      PreCalls pc;
      auto sl = [&](nrt_tensor_t* t, size_t bytes) { return dev_slice(t, bytes, "slice"); };
      size_t xb = (size_t)T * H * bf, qb = (size_t)NQ / 2 * T * D * bf, kb = (size_t)NKV / 2 * T * D * bf;
      pc.toks = sl(toks_, (size_t)T * 4);
      nrt_tensor_t* x[2] = {sl(xp_[0], xb), sl(xp_[1], xb)};
      nrt_tensor_t *q[2], *k[2], *v[2], *a[2], *m[2];
      for (int i = 0; i < 2; i++) { q[i] = sl(q_[i], qb); k[i] = sl(k_[i], kb); v[i] = sl(v_[i], kb); a[i] = sl(a_[i], qb); }
      for (int c = 0; c < 2; c++) m[c] = sl(m_[c], xb);
      nrt_tensor_t* h = sl(hp_, xb);
      nrt_tensor_t* cs = sl(rope_cos_, (size_t)T * D * bf);
      nrt_tensor_t* sn = sl(rope_sin_, (size_t)T * D * bf);
      {  // own prefill kernels on the X layout (kernels/qwen3.py): embed_x, then per layer qkv3 / attn2 / post3
        const int TB = std::min(T, 512);
        size_t qs = (size_t)NQ * T * D * bf, ks = (size_t)NKV * T * D * bf;
        nrt_tensor_t *qq = sl(q_[0], qs), *kk = sl(k_[0], ks), *vv = sl(v_[0], ks);
        nrt_tensor_t *aa = sl(a_[0], qs), *a0 = dev_slice(a_[0], qs / 2, "a0"), *a1 = dev_slice(a_[0], qs / 2, "a1", qs / 2);
        pc.embed = make_call("embed_x" + s, {{"toks", pc.toks}, {"emb", emb_}}, {x[0]});
        auto G1 = [&](const char* k, int l) { return group(k, l, 1); };
        for (int l = 0; l < L; l++) {
          LayerW& w = lw_[l];
          nrt_tensor_t* xi = x[l % 2];
          nrt_tensor_t* xo = x[(l + 1) % 2];
          if (qkva_T(T) && l != L - 1) continue;   // in pre_layers groups below
          pc.qkv.push_back(make_call("pre_qkv3" + s, {{"X", xi}, {"g1c", G1("g1c", l)}, {"wqkv", G1("wqkv", l)}, {"qn", G1("qn", l)},
                                                      {"kn", G1("kn", l)}, {"rcT", rcT_}, {"rsT", rsT_}, {"rot", rot_},
                                                      {"kc", G1("kc", l)}, {"vc", G1("vc", l)}},
                                     {qq, kk, vv}));
          if (qkva_T(T)) continue;
          pc.attn.push_back(make_call("pre_attn2" + s, {{"q", qq}, {"k", kk}, {"v", vv}}, {a0, a1}));
          pc.post.push_back(make_call("pre_post3" + s, {{"X", xi}, {"a", aa}, {"wo", G1("wo", l)}, {"g2c", G1("g2c", l)},
                                                       {"wg", G1("wg", l)}, {"wu", G1("wu", l)}, {"wd", G1("wd", l)}}, {xo}));
        }
        if (qkva_T(T)) {   // layers 0 .. L-2 in groups of NLP; their output lands where layer L-1 reads it
          for (int g = 0; g < (L - 1) / NLP; g++) {
            int l0 = g * NLP;
            auto G = [&](const char* k) { return group(k, l0, NLP); };
            nrt_tensor_t* xi = x[(g * NLP) % 2 == 0 ? (g % 2) : (g % 2)];
            pc.layers.push_back(make_call("pre_layers" + s,
                                          {{"X", x[g % 2]}, {"g1c", G("g1c")}, {"wqkv", G("wqkv")}, {"qn", G("qn")}, {"kn", G("kn")},
                                           {"rcT", rcT_}, {"rsT", rsT_}, {"rot", rot_}, {"kc", G("kc")}, {"vc", G("vc")},
                                           {"wo", G("wo")}, {"g2c", G("g2c")}, {"wg", G("wg")}, {"wu", G("wu")}, {"wd", G("wd")}},
                                          {x[(g + 1) % 2]}));
            (void)xi;
          }
          // the last layer's qkv3 above reads x[(L-1) % 2]; the groups end in x[((L-1)/NLP) % 2]
          if (((L - 1) / NLP) % 2 != (L - 1) % 2) die("prefill buffer parity");
        }
        pc.xrow = make_call("x_row" + s, {{"X", x[(L - 1) % 2]}, {"off", off_}}, {xd_[0]});  // input of the last layer
        pc.tb = TB;
        pc.xout = x[L % 2];
        pre_[T] = std::move(pc);
        continue;
      }
      for (int l = 0; l < L; l++) {
        LayerW& w = lw_[l];
        nrt_tensor_t* xi = x[l % 2];
        nrt_tensor_t* xo = x[(l + 1) % 2];
        pc.qkv.push_back(make_call("pre_qkv" + s, {{"x", xi}, {"g1", w.g1}, {"wqkv", w.wqkv}, {"qn", w.qn}, {"kn", w.kn}, {"cos", cs}, {"sin", sn}},
                                   {q[0], q[1], k[0], k[1], v[0], v[1]}));
        pc.cache.push_back(make_call("pre_cache" + s, {{"k0", k[0]}, {"k1", k[1]}, {"v0", v[0]}, {"v1", v[1]}, {"kc", w.kc}, {"vc", w.vc}}, {dummy_}));
        pc.attn.push_back(make_call("pre_attn" + s, {{"q0", q[0]}, {"q1", q[1]}, {"k0", k[0]}, {"k1", k[1]}, {"v0", v[0]}, {"v1", v[1]}}, {a[0], a[1]}));
        pc.oproj.push_back(make_call("pre_oproj" + s, {{"x", xi}, {"a0", a[0]}, {"a1", a[1]}, {"wo", w.wo}}, {h}));
        // residual stream: acc_0 = h, acc_{c+1} = acc_c + mlp_c(h); the last chunk writes the layer output
        const int nc = nch(T);
        for (int c = 0; c < nc; c++)
          pc.mlp[c].push_back(make_call("pre_mlp" + std::to_string(c) + s,
                                        {{"h", h}, {"acc", c == 0 ? h : m[(c - 1) % 2]}, {"g2", w.g2}, {"wg", w.wg},
                                         {"wu", w.wu}, {"wd", w.wd}, {"chunk", chunk_[nc][c]}},
                                        {c == nc - 1 ? xo : m[c % 2]}));
      }
      pc.xout = x[L % 2];
      pre_[T] = std::move(pc);
    }
  }

  // ---------------------------------------------------------------------------------------------- execution
  std::vector<std::pair<nrta_seq_t, NRT_STATUS*>> inflight_;
  std::vector<std::unique_ptr<NRT_STATUS>> statuses_;
  size_t nst_ = 0;

  void run(const Call& c) {
    if (nst_ == statuses_.size()) statuses_.push_back(std::make_unique<NRT_STATUS>());
    NRT_STATUS* st = statuses_[nst_++].get();
    *st = NRT_SUCCESS;
    nrta_seq_t seq;
    NRT_STATUS s;
    auto ts0 = clk::now();
    while ((s = nrta_execute_schedule(c.model->m, c.ins, c.outs, 0, st, &seq)) == NRT_QUEUE_FULL) {}
    if (prof_) prof_ms_["~sched " + c.model->name] += ms_since(ts0), prof_n_["~sched " + c.model->name]++;
    if (s != NRT_SUCCESS) throw std::runtime_error("nrta_execute_schedule(" + c.model->name + ") -> " + std::to_string((int)s));
    inflight_.push_back({seq, st});
    if (prof_) {
      auto t = clk::now();
      wait_all();
      prof_ms_[c.model->name] += ms_since(t);
      prof_n_[c.model->name]++;
    }
  }
  void prof_report() {
    if (!prof_) return;
    double tot = 0;
    for (auto& [n, ms] : prof_ms_) tot += ms;
    for (auto& [n, ms] : prof_ms_) fprintf(stderr, "  prof %-18s n=%5d total %8.2f ms  per call %8.3f ms\n", n.c_str(), prof_n_[n], ms, ms / prof_n_[n]);
    fprintf(stderr, "  prof total %.1f ms\n", tot);
    prof_ms_.clear(); prof_n_.clear();
  }
  void wait_all() {
    if (inflight_.empty()) return;
    nrta_seq_t last = inflight_.back().first;
    bool done = false;
    while (!done) CK(nrta_is_completed(last, &done));
    for (auto& [seq, st] : inflight_)
      if (*st != NRT_SUCCESS) { inflight_.clear(); nst_ = 0; throw std::runtime_error("execution failed: " + std::to_string((int)*st)); }
    inflight_.clear();
    nst_ = 0;
  }

  int read_token() {
    uint32_t idx;
    CK(nrt_tensor_read(amax_i_, &idx, 0, 4));
    if (idx >= (uint32_t)V) throw std::runtime_error("argmax out of range");
    return (int)idx;
  }

  int prefill(const std::vector<int>& prompt) {
    int P = (int)prompt.size();
    int T = 0;
    for (int b : PRE_T) if (b >= P) { T = b; break; }
    PreCalls& pc = pre_.at(T);
    std::vector<int32_t> toks(T, 0);
    for (int i = 0; i < P; i++) toks[i] = prompt[i];
    auto tw0 = clk::now();
    CK(nrt_tensor_write(pc.toks, toks.data(), 0, (size_t)T * 4));
    // token P - 1 goes through the last layer on the decode kernel at position P - 1; its input row is
    // X[b, :, :, t] of the last layer's input, b * TB + t = P - 1
    int32_t off = (int32_t)(((P - 1) / pc.tb) * 128 * (H / 128) * pc.tb + (P - 1) % pc.tb);
    int32_t p1 = P - 1;
    float pf = (float)(P - 1);
    CK(nrt_tensor_write(off_, &off, 0, 4));
    CK(nrt_tensor_write(pos_, &p1, 0, 4));
    CK(nrt_tensor_write(posf_, &pf, 0, 4));
    int si = -1;
    for (size_t i = 0; i < std::size(DEC_S); i++) if (DEC_S[i] > P - 1) { si = (int)i; break; }
    if (prof_) fprintf(stderr, "  prefill host writes %.3f ms\n", ms_since(tw0));
    run(pc.embed);
    if (!pc.layers.empty()) {
      for (auto& c : pc.layers) run(c);
      run(pc.qkv[0]);   // the last layer: K/V of every prompt token into the cache; the rest for token P - 1 below
    } else {
      for (int l = 0; l < L; l++) {
        run(pc.qkv[l]);
        if (l == L - 1) break;   // the last layer: K/V into the cache only
        run(pc.attn[l]);
        run(pc.post[l]);
      }
    }
    for (int l = 0; l < L && !pc.small; l++) {
      run(pc.qkv[l]);
      run(pc.cache[l]);
      run(pc.attn[l]);
      run(pc.oproj[l]);
      for (int c = 0; c < nch(T); c++) run(pc.mlp[c][l]);
    }
    run(pc.xrow);
    run(dec_.last[si]);
    run(dec_.head);
    run(dec_.amax);
    wait_all();
    return read_token();
  }

  int decode_step(int tok, int pos) {
    int si = -1;
    for (size_t i = 0; i < std::size(DEC_S); i++) if (DEC_S[i] > pos) { si = (int)i; break; }
    if (si < 0) throw std::runtime_error("position beyond the KV cache");
    int32_t t = tok, p = pos;
    auto t0 = clk::now();
    CK(nrt_tensor_write(tok_, &t, 0, 4));
    CK(nrt_tensor_write(pos_, &p, 0, 4));
    double tw = ms_since(t0);
    run(dec_.embed);
    if (step_t_ && ms_since(last_wait_end_) < 5.0) step_gap_ms_ += ms_since(last_wait_end_), step_w_ms_ += tw, step_pre_ms_ += std::chrono::duration<double, std::milli>(t0 - last_wait_end_).count(), step_n_++;
    for (auto& c : dec_.layer[si]) run(c);
    run(dec_.head);
    run(dec_.amax);
    double ts = ms_since(t0);
    wait_all();
    double tq = ms_since(t0);
    int r = read_token();
    last_wait_end_ = clk::now();
    if (prof_) fprintf(stderr, "  step: write %.3f sched %.3f wait %.3f read %.3f ms\n", tw, ts, tq, ms_since(t0));
    return r;
  }
};

// ------------------------------------------------------------------------------------------------ protocol loop
// One request line from stdin. The host thread spins (non-blocking reads) for up to SPIN_S seconds after the last
// request before it blocks in read(): a process asleep in read() answers the next request measurably later.
static bool read_line(std::string& line) {
  static std::string buf;
  static bool eof = false;
  static const double SPIN_S = getenv("ENGINE_NOSPIN") ? 0.0 : 10.0;
  line.clear();
  for (;;) {
    size_t nl = buf.find('\n');
    if (nl != std::string::npos) {
      line.assign(buf, 0, nl);
      buf.erase(0, nl + 1);
      return true;
    }
    if (eof) {
      if (buf.empty()) return false;
      line.swap(buf);
      return true;
    }
    char tmp[1 << 16];
    auto t0 = clk::now();
    ssize_t n;
    for (;;) {
      n = read(0, tmp, sizeof tmp);
      if (n >= 0 || (errno != EAGAIN && errno != EWOULDBLOCK)) break;
      if (ms_since(t0) > SPIN_S * 1e3) {   // idle: block until the next request
        int fl = fcntl(0, F_GETFL);
        fcntl(0, F_SETFL, fl & ~O_NONBLOCK);
        n = read(0, tmp, sizeof tmp);
        fcntl(0, F_SETFL, fl | O_NONBLOCK);
        break;
      }
    }
    if (n <= 0) { eof = true; continue; }
    buf.append(tmp, (size_t)n);
  }
}

int main(int argc, char** argv) {
  std::string model_dir;
  for (int i = 1; i < argc; i++)
    if (!strcmp(argv[i], "--model") && i + 1 < argc) model_dir = argv[++i];
  if (model_dir.empty()) { fprintf(stderr, "usage: %s --model MODEL_DIR\n", argv[0]); return 2; }
  // stdout carries replies only: keep a private copy of it and send everything else written to fd 1 to stderr
  int out_fd = dup(1);
  dup2(2, 1);
  FILE* out = fdopen(out_fd, "w");
  Engine eng(model_dir);
  bool loaded = false;
  std::string line;
  fcntl(0, F_SETFL, fcntl(0, F_GETFL) | O_NONBLOCK);
  while (read_line(line)) {
    if (line.empty()) continue;
    std::string id = "null";
    std::string reply;
    try {
      json::Value req = json::parse(line);
      if (auto* v = req.get("id")) id = v->kind == json::Value::Num ? std::to_string(v->as_int()) : json::quote(v->s);
      std::string op = req.at("op").s;
      if (op == "hello") {
        if (!loaded) { eng.load(); loaded = true; }
        reply = "{\"id\":" + id + ",\"ok\":true,\"protocol\":1}";
      } else if (op == "generate") {
        if (!loaded) { eng.load(); loaded = true; }
        std::vector<int> prompt;
        for (auto& t : req.at("prompt").arr) prompt.push_back((int)t.as_int());
        int n = (int)req.at("max_tokens").as_int();
        bool reset = req.at("reset").b;
        auto t0 = clk::now();
        std::vector<int> toks = eng.generate(prompt, n, reset);
        fprintf(stderr, "generate P=%zu n=%d reset=%d: %.1f ms\n", prompt.size(), n, (int)reset, ms_since(t0));
        eng.report();
        eng.step_report();
        reply = "{\"id\":" + id + ",\"ok\":true,\"tokens\":[";
        for (size_t i = 0; i < toks.size(); i++) { if (i) reply += ","; reply += std::to_string(toks[i]); }
        reply += "]}";
      } else {
        throw std::runtime_error("unknown op " + op);
      }
    } catch (std::exception& e) {
      fprintf(stderr, "error: %s\n", e.what());
      reply = "{\"id\":" + id + ",\"ok\":false,\"error\":" + json::quote(e.what()) + "}";
    }
    fprintf(out, "%s\n", reply.c_str());
    fflush(out);
  }
  nrt_close();
  return 0;
}
